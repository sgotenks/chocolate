/**
 * product-cards — alternating product cards with a "See more details" disclosure.
 * Reconstructive: one authored row per card; cells classified by content —
 *   the cell with an image = product shot; the cell whose heading is the largest (h2/h3) =
 *   summary (name, title, description); the cell with h4 sections = details (lead copy, then one
 *   group per h4: Ingredients text, the nutrition facts list — nested list = sub-rows, bold =
 *   daily value — and the small print after it).
 * Every authored node is MOVED into the card template; nothing is rebuilt from text.
 * @ew-exempt disclosure toggle label — UI chrome generated by the block, not authored
 * @ew-exempt facts caption — screen-reader label derived from the group heading (source caption)
 */
const ASSETS = `${window.hlx?.codeBasePath || ''}/blocks/product-cards/assets`;
const OPEN_LABEL = 'See more details';
const CLOSE_LABEL = 'See less details';
const CHEVRON = '<svg viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg"'
  + ' aria-hidden="true">'
  + '<path d="M12.0001 15.8522L5.54785 9.39998L7.4001 7.54773L12.0001 12.1477L16.6001 7.54773'
  + 'L18.4524 9.39998L12.0001 15.8522Z" fill="currentColor"/></svg>';

const el = (tag, className, attrs = {}) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  Object.entries(attrs).forEach(([k, v]) => node.setAttribute(k, v));
  return node;
};

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** wraps the own (non-list) children of each list item into a row span: label + value */
function decorateFacts(list) {
  list.classList.add('pcard-facts');
  const rows = [];
  list.querySelectorAll('li').forEach((li) => {
    const row = el('span', 'pcard-fact');
    const nested = li.querySelector(':scope > ul, :scope > ol');
    [...li.childNodes].forEach((n) => {
      if (n !== nested) row.append(n);
    });
    li.prepend(row);
    rows.push(row);
  });
  if (rows.length) rows[rows.length - 1].classList.add('pcard-fact-last');
}

/** splits the details cell into lead, one group per h4, and trailing small print */
function buildDetails(cell, body) {
  const lead = el('div', 'pcard-lead');
  let group = null;
  let afterList = false;
  [...cell.children].forEach((node) => {
    if (/^H[1-6]$/.test(node.tagName)) {
      group = el('div', 'pcard-block');
      group.append(node);
      body.append(group);
      afterList = false;
      return;
    }
    if (!group) {
      lead.append(node);
      return;
    }
    if (node.tagName === 'UL' || node.tagName === 'OL') {
      group.classList.add('pcard-block-table');
      decorateFacts(node);
      const heading = group.querySelector('h1, h2, h3, h4, h5, h6');
      if (heading) {
        const caption = el('span', 'visually-hidden pcard-facts-caption');
        caption.textContent = heading.textContent;
        group.append(caption);
      }
      group.append(node);
      afterList = true;
      return;
    }
    const small = el('div', 'pcard-small');
    small.append(node);
    if (afterList) body.append(small);
    else group.append(small);
  });
  if (lead.childNodes.length) body.prepend(lead);
}

function buildToggle(card, panel, id) {
  const row = el('div', 'pcard-toggle-row');
  const toggle = el('button', 'btn btn-text pcard-toggle', {
    id: `product-card-toggle-${id}`,
    type: 'button',
    'aria-expanded': 'false',
    'aria-controls': panel.id,
  });
  const icon = () => {
    const span = el('span', 'btn-icon', { 'aria-hidden': 'true' });
    span.innerHTML = CHEVRON;
    return span;
  };
  const label = el('span', 'pcard-toggle-label');
  label.textContent = OPEN_LABEL;
  toggle.append(icon(), label, icon());
  panel.setAttribute('aria-labelledby', toggle.id);
  toggle.addEventListener('click', () => {
    const open = toggle.getAttribute('aria-expanded') !== 'true';
    toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
    panel.dataset.expanded = open ? 'true' : 'false';
    panel.setAttribute('aria-hidden', open ? 'false' : 'true');
    if (open) panel.removeAttribute('inert');
    else panel.setAttribute('inert', '');
    label.textContent = open ? CLOSE_LABEL : OPEN_LABEL;
    if (!open) {
      const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
      card.scrollIntoView({ block: 'start', behavior: reduce ? 'auto' : 'smooth' });
    }
  });
  row.append(toggle);
  return row;
}

function buildCard(row, index) {
  const cells = [...row.children];
  const mediaCell = cells.find((c) => c.querySelector('picture, img') && !c.querySelector('h4'));
  const detailsCell = cells.find((c) => c.querySelector('h4'));
  const summaryCell = cells.find((c) => c !== mediaCell && c !== detailsCell);

  const card = el('article', `pcard${index % 2 ? ' pcard-flip' : ''}`);
  const container = el('div', 'pcard-container');
  const stars = el('div', 'pcard-stars', { 'aria-hidden': 'true' });
  stars.append(el('img', '', {
    src: `${ASSETS}/stars.webp`, alt: '', width: '741', height: '600', loading: 'lazy',
  }));
  const body = el('div', 'pcard-body');
  const cardRow = el('div', 'pcard-row');
  const media = el('div', 'pcard-media');
  const text = el('div', 'pcard-text');
  const titles = el('div', 'pcard-titles');
  const desc = el('div', 'pcard-desc');

  if (mediaCell) media.append(...mediaCell.childNodes);
  let title = '';
  if (summaryCell) {
    const heading = summaryCell.querySelector('h1, h2, h3, h4, h5, h6');
    title = heading ? heading.textContent : '';
    let seenHeading = false;
    [...summaryCell.children].forEach((node) => {
      if (node === heading) {
        titles.append(node);
        seenHeading = true;
      } else if (!seenHeading) titles.append(node);
      else desc.append(node);
    });
  }
  text.append(titles, desc, el('div', 'pcard-cta'));
  cardRow.append(media, text);

  const id = `${slug(title) || 'product'}-${index + 1}`;
  const details = el('div', 'pcard-details');
  const panel = el('div', 'pcard-panel', {
    id: `product-card-panel-${id}`,
    'data-expanded': 'false',
    role: 'region',
    'aria-hidden': 'true',
    inert: '',
  });
  const inner = el('div', 'pcard-panel-inner');
  const panelBody = el('div', 'pcard-panel-body');
  if (detailsCell) buildDetails(detailsCell, panelBody);
  inner.append(panelBody);
  panel.append(inner);
  details.append(panel, buildToggle(card, panel, id));

  body.append(
    cardRow,
    el('div', 'pcard-rule pcard-rule-md', { 'aria-hidden': 'true' }),
    details,
    el('div', 'pcard-rule pcard-rule-sm', { 'aria-hidden': 'true' }),
    el('div', 'pcard-foot'),
  );
  container.append(stars, body);
  card.append(container);
  return card;
}

export default function decorate(block) {
  if (block.querySelector(':scope > .pcard')) return;
  if (!document.getElementById('product-section')) block.id = 'product-section';
  const rows = [...block.children];
  const cards = rows.map((row, i) => buildCard(row, i));
  rows.forEach((row) => row.remove());
  block.append(...cards);
}
